function [tab,summary]=m1_trace(c,o,initial_kmh,final_kmh,acceleration_g,dt,id)
% Prescribed constant-acceleration pulse. Infeasible traces remain flagged.
g=c.base.vehicle.gravity_m_s2;
a=acceleration_g*g; u=initial_kmh/3.6; w=final_kmh/3.6;
duration=(w-u)/a;
assert(duration>0 && dt>0,'m1:Trace','Require positive duration and sampling step');
t=linspace(0,duration,ceil(duration/dt)+1)'; speed=u+a*t; speed(end)=w;
records=cell(numel(t),1);
for k=1:numel(t)
    records{k}=m1_point(c,max(0,speed(k)),a,o);
end
fields=fieldnames(records{1}); tab=table(t,'VariableNames',{'time_s'});
for k=1:numel(fields)
    key=fields{k}; value=cellfun(@(q)q.(key),records,'UniformOutput',false); value=vertcat(value{:});
    if size(value,2)==2
        tab.([key '_left'])=value(:,1); tab.([key '_right'])=value(:,2);
    else
        tab.(key)=value;
    end
end
integrate=@(x)trapz(t,x);
Ekin=.5*c.base.vehicle.mass_kg*c.base.vehicle.rotational_inertia_factor*(w^2-u^2);
Edc=integrate(tab.dc_power_total_W);
Efront=integrate(tab.front_axle_friction_power_W);
Edisc=integrate([tab.disc_contact_power_W_left tab.disc_contact_power_W_right]);
Egear=integrate([tab.gear_heat_assumed_W_left tab.gear_heat_assumed_W_right]);
Eemot=integrate([tab.emot_combined_heat_W_left tab.emot_combined_heat_W_right]);
Eroad=integrate(tab.road_power_W); Egrade=integrate(tab.grade_power_W);
Elr=integrate(tab.lr_kinematic_exchange_W); Eunmet=integrate(tab.unmet_power_W);
Eaux=integrate(tab.auxiliary_power_W);
residual=Edc+Eunmet-Ekin-Efront-sum(Edisc)-sum(Egear)-sum(Eemot)-Eroad-Egrade-Elr-Eaux;
driving=tab.motor_torque_Nm_left>0;
if any(driving)
    driveCoverage=mean(isfinite(tab.motor_total_heat_estimated_W_left(driving)));
else
    driveCoverage=NaN; % a braking-only trace has no drive-split coverage statistic
end
summary=struct('case_id',id,'initial_speed_kmh',initial_kmh,'final_speed_kmh',final_kmh, ...
    'acceleration_g',acceleration_g,'duration_s',duration,'sample_count',numel(t),'road_load',o.road_load, ...
    'battery_charge_cap_total_kW',o.battery_charge_cap_total_kW, ...
    'initial_left_disc_torque_Nm',tab.disc_friction_torque_Nm_left(1), ...
    'peak_left_disc_torque_Nm',max(tab.disc_friction_torque_Nm_left), ...
    'initial_left_disc_power_kW',tab.disc_contact_power_W_left(1)/1000, ...
    'peak_left_disc_power_kW',max(tab.disc_contact_power_W_left)/1000, ...
    'left_disc_contact_energy_kJ',Edisc(1)/1000,'right_disc_contact_energy_kJ',Edisc(2)/1000, ...
    'front_axle_friction_energy_kJ',Efront/1000,'battery_net_energy_kJ',Edc/1000, ...
    'gear_heat_energy_total_kJ',sum(Egear)/1000,'emot_heat_energy_total_kJ',sum(Eemot)/1000, ...
    'road_energy_kJ',Eroad/1000,'grade_energy_kJ',Egrade/1000,'lr_exchange_energy_kJ',Elr/1000, ...
    'kinetic_energy_change_kJ',Ekin/1000,'unmet_energy_kJ',Eunmet/1000, ...
    'energy_residual_relative',abs(residual)/max(1,abs(Ekin)), ...
    'max_power_residual_W',max(abs(tab.power_residual_W)), ...
    'trace_feasible',all(tab.trace_feasible),'max_unmet_force_N',max(abs(tab.unmet_force_N)), ...
    'peak_total_battery_charge_kW',max(0,-min(tab.dc_power_total_W))/1000, ...
    'unknown_winding_sample_count',sum(isnan(tab.winding_heat_W_left)), ...
    'drive_split_covered_fraction',driveCoverage, ...
    'max_motor_speed_left_rpm',max(tab.motor_rpm_left),'max_motor_speed_right_rpm',max(tab.motor_rpm_right));
end
