function m1_check_trace_provenance(c,saved)
% Reject source export from dynamics computed with another input snapshot.
assert(isstruct(saved) && isfield(saved,'input_sha256') && isfield(saved,'code_commit') && ...
    isfield(saved,'baseline_commit') && isequaln(saved.input_sha256,c.provenance.input_sha256) && ...
    strcmp(saved.code_commit,c.provenance.code_commit) && strcmp(saved.baseline_commit,c.provenance.baseline_commit), ...
    'm1:StaleTrace','Re-run run_m1 with the same prepared inputs before exporting engineering sources');
end
